// src/Wc3.Commands/TriggerToScriptCommand.cs
using System.Text;
using Wc3.GameData;
using Wc3.Model;

namespace Wc3.Commands;

/// <summary>Result of rendering a GUI trigger tree to JASS-style text. <see cref="Script"/> is
/// the text, <see cref="CatalogApplied"/> says whether a World-Editor catalog was supplied so
/// preset values could be resolved to their script form.</summary>
public sealed record TriggerScriptResult(
    string Script,
    int Triggers,
    int CustomTextTriggers,
    int Functions,
    bool CatalogApplied,
    IReadOnlyList<string> Notes);

/// <summary>
/// Renders the GUI trigger tree (war3map.wtg) to JASS-style text, the way the World Editor's
/// "convert to custom text" presents one trigger. Read-only, and it never edits the map.
/// </summary>
/// <remarks>
/// <para>This is a READABLE rendering rather than a byte-exact reproduction of the World Editor
/// output, and it says so in its own header. Two things make exactness out of reach here. The
/// compiled script is produced only by the World Editor, which wc3ctl deliberately refuses to
/// imitate (regenerating war3map.j would clobber hand-written or externally built code, see
/// <see cref="TriggerRecoverCommand"/>). And a function's GUI name is not always its JASS name,
/// the World-Editor table carries a separate script name that the catalog parser does not keep.</para>
///
/// <para>What it does resolve through the catalog is a parameter whose value names a catalog
/// PRESET, which is emitted as that preset's script text (the table's own <c>ScriptText</c>, for
/// example the arithmetic operator <c>OperatorAdd</c> becomes <c>+</c>). Every other name is used
/// as stored. With no catalog the rendering still works and simply keeps the raw preset name.</para>
///
/// <para>A custom-text trigger holds its body as JASS in war3map.wct rather than as a list of
/// functions, so its body is emitted verbatim rather than reconstructed.</para>
/// </remarks>
public static class TriggerToScriptCommand
{
    public static TriggerScriptResult Render(MapDocument doc, TriggerDataCatalog? catalog = null)
    {
        var model = TriggerReadCommand.GetTriggers(doc);
        var notes = new List<string>();

        var sb = new StringBuilder();
        sb.AppendLine("// Generated by wc3ctl 'trigger to-script'. A JASS-style rendering of the World");
        sb.AppendLine("// Editor trigger tree, for reading rather than for compiling. Function names are used");
        sb.AppendLine("// as the tree stores them and preset values are resolved through the World-Editor");
        sb.AppendLine("// catalog only when one was supplied, so this is not a replacement for the compiled");
        sb.AppendLine($"// script. The map's script language is {model.ScriptLanguage}.");
        sb.AppendLine();

        int functions = 0;
        int customText = 0;
        foreach (var trigger in model.Triggers)
        {
            if (trigger.IsCustomText)
            {
                customText++;
                AppendCustomText(sb, trigger);
                continue;
            }

            functions += trigger.Functions.Count;
            AppendGuiTrigger(sb, trigger, catalog);
        }

        if (model.Triggers.Count == 0)
            sb.AppendLine("// This map has no GUI trigger tree. Its logic is in the compiled script.");

        if (catalog is null)
            notes.Add(
                "no World-Editor catalog was available, so preset values keep their raw names and "
                + "the rendering is less resolved than it could be. Pass a TriggerData.txt or a game "
                + "directory to resolve them.");
        notes.Add(
            "nested control blocks (if/then/else, loops) render as their GUI function name with "
            + "arguments rather than as generated helper functions, so the text reads but does not compile.");

        return new TriggerScriptResult(
            sb.ToString().TrimEnd() + "\n",
            model.Triggers.Count,
            customText,
            functions,
            catalog is not null,
            notes);
    }

    private static void AppendCustomText(StringBuilder sb, TriggerInfo trigger)
    {
        sb.AppendLine("//===========================================================================");
        sb.AppendLine($"// {trigger.Name} (custom text)");
        sb.AppendLine("//===========================================================================");
        sb.AppendLine((trigger.CustomText ?? string.Empty).TrimEnd());
        sb.AppendLine();
    }

    private static void AppendGuiTrigger(StringBuilder sb, TriggerInfo trigger, TriggerDataCatalog? catalog)
    {
        string ident = Ident(trigger.Name, trigger.Id);
        string handle = "gg_trg_" + ident;

        sb.AppendLine("//===========================================================================");
        sb.AppendLine($"// {trigger.Name}");
        sb.AppendLine("//===========================================================================");

        var events = trigger.Functions.Where(f => f.Kind == "Event").ToList();
        var conditions = trigger.Functions.Where(f => f.Kind == "Condition").ToList();
        var actions = trigger.Functions.Where(f => f.Kind == "Action").ToList();

        if (conditions.Count > 0)
        {
            sb.AppendLine($"function Trig_{ident}_Conditions takes nothing returns boolean");
            sb.AppendLine($"    return {string.Join(" and ", conditions.Select(c => Call(c, catalog)))}");
            sb.AppendLine("endfunction");
            sb.AppendLine();
        }

        sb.AppendLine($"function Trig_{ident}_Actions takes nothing returns nothing");
        if (actions.Count == 0)
        {
            sb.AppendLine("    // no actions");
        }
        else
        {
            foreach (var action in actions)
            {
                if (!action.Enabled) sb.Append("    // Disabled action ");
                else sb.Append("    call ");
                sb.AppendLine(Call(action, catalog));
            }
        }
        sb.AppendLine("endfunction");
        sb.AppendLine();

        sb.AppendLine($"function InitTrig_{ident} takes nothing returns nothing");
        sb.AppendLine($"    set {handle} = CreateTrigger(  )");
        foreach (var ev in events)
        {
            string args = ev.Parameters.Count == 0
                ? $" {handle} "
                : $" {handle}, {string.Join(", ", ev.Parameters.Select(p => Resolve(p, catalog)))} ";
            sb.AppendLine($"    call {ev.Name}({args})");
        }
        if (conditions.Count > 0)
            sb.AppendLine($"    call TriggerAddCondition( {handle}, Condition( function Trig_{ident}_Conditions ) )");
        sb.AppendLine($"    call TriggerAddAction( {handle}, function Trig_{ident}_Actions )");
        sb.AppendLine("endfunction");
        sb.AppendLine();
    }

    /// <summary>A function call in script form, as <c>Name( a, b )</c> or <c>Name(  )</c> with no
    /// arguments, matching the World Editor's spacing.</summary>
    private static string Call(TriggerFunctionInfo f, TriggerDataCatalog? catalog)
    {
        if (f.Parameters.Count == 0) return $"{f.Name}(  )";
        return $"{f.Name}( {string.Join(", ", f.Parameters.Select(p => Resolve(p, catalog)))} )";
    }

    /// <summary>A single rendered parameter, with a catalog preset name turned into its script
    /// text when a catalog knows it.</summary>
    private static string Resolve(string rendered, TriggerDataCatalog? catalog) =>
        catalog?.FindParam(rendered)?.ScriptText ?? rendered;

    /// <summary>A JASS identifier safe in a function name, where anything that is not a letter,
    /// digit or underscore becomes an underscore. A blank name falls back to the item id.</summary>
    private static string Ident(string name, int id)
    {
        string raw = string.IsNullOrWhiteSpace(name) ? $"trigger_{id}" : name.Trim();
        var sb = new StringBuilder(raw.Length);
        foreach (char ch in raw)
            sb.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        return sb.Length == 0 ? $"trigger_{id}" : sb.ToString();
    }
}
