// src/Wc3.Commands/LeakHarnessCommand.cs
using System.Text;
using Wc3.Model;

namespace Wc3.Commands;

/// <summary>A generated in-map harness. Source is the text written to SavedTo, and Functions names
/// the leak candidates it drives on the short timer.</summary>
public sealed record LeakHarnessResult(
    bool Ok,
    string Message,
    string Language,
    string Target,
    IReadOnlyList<string> Functions,
    string Source,
    string? SavedTo);

/// <summary>
/// Emits a small harness in the map's own language that drives the named hot leak candidates on a
/// short timer, so the runtime handle and memory slope is measurable in seconds rather than in an
/// hour, plus a sampler that writes a handle reading. The harness is text for the map to run, not a
/// game launch, and it is checked as valid syntax for the language it is written in.
///
/// The call target is a function the static list flagged hot, which means a periodic callback. The
/// harness assumes each such function takes nothing and returns nothing, which is what a timer or
/// trigger callback has to be. The engine entry points are never driven, so a leak inside main or
/// config cannot be looped this way.
/// </summary>
public static class LeakHarnessCommand
{
    private static readonly HashSet<string> NeverDrive = new(StringComparer.Ordinal)
    {
        "main", "config", "InitCustomTriggers", "RunInitializationTriggers",
    };

    public static LeakHarnessResult Execute(MapDocument doc, string lang, string target, string? outPath)
        => Build(LeakListCommand.Execute(doc), lang, target, outPath);

    public static LeakHarnessResult Build(
        LeakListResult list, string lang, string target, string? outPath = null)
    {
        lang = (lang ?? "").Trim().ToLowerInvariant();
        if (lang is not ("jass" or "lua"))
            return Fail("jass", target, "--lang must be jass or lua");

        var available = list.Targets
            .Select(t => t.Function)
            .Where(f => !NeverDrive.Contains(f))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(f => f, StringComparer.Ordinal)
            .ToList();
        if (available.Count == 0)
            return Fail(lang, target, "no hot leak candidates to drive, every finding runs once or in repeated code");

        var selected = new List<string>();
        if (string.Equals(target, "all", StringComparison.OrdinalIgnoreCase))
        {
            selected.AddRange(available);
        }
        else
        {
            // A target names a leak candidate, either by the function that leaks or by the handle
            // kind it leaks. Both select the functions the harness drives.
            var byName = list.Targets
                .Where(t => !NeverDrive.Contains(t.Function)
                    && string.Equals(t.Function, target, StringComparison.OrdinalIgnoreCase))
                .Select(t => t.Function);
            var byKind = list.Targets
                .Where(t => !NeverDrive.Contains(t.Function)
                    && string.Equals(t.Handle, target, StringComparison.OrdinalIgnoreCase))
                .Select(t => t.Function);
            selected.AddRange(byName.Concat(byKind)
                .Distinct(StringComparer.Ordinal).OrderBy(f => f, StringComparer.Ordinal));
            if (selected.Count == 0)
                return Fail(lang, target,
                    $"no hot leak candidate named '{target}', available are {string.Join(", ", available)}");
        }

        string source = lang == "jass" ? Jass(selected) : Lua(selected);
        string? saved = null;
        if (!string.IsNullOrWhiteSpace(outPath))
        {
            if (Path.GetDirectoryName(Path.GetFullPath(outPath)) is { Length: > 0 } dir)
                Directory.CreateDirectory(dir);
            File.WriteAllText(outPath, source, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            saved = Path.GetFullPath(outPath);
        }

        string message = $"wrote a {lang} harness driving {selected.Count} hot leak candidate(s) "
            + $"on a 0.03 s timer with a 1 s handle sampler" + (saved is null ? "" : $", saved {saved}");
        return new(true, message, lang, target, selected, source, saved);
    }

    private static LeakHarnessResult Fail(string lang, string target, string message) =>
        new(false, message, lang, target, Array.Empty<string>(), "", null);

    private static string Jass(IReadOnlyList<string> functions)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// leak harness, generated by wc3ctl");
        sb.AppendLine("// Drives the named hot leak candidates on a short timer so the runtime handle");
        sb.AppendLine("// and memory slope becomes measurable in seconds rather than in an hour.");
        sb.AppendLine("// Each driven function is a periodic callback that must take nothing.");
        sb.AppendLine();
        sb.AppendLine("function LeakHarnessSample takes nothing returns nothing");
        sb.AppendLine("    local trigger probe = CreateTrigger()");
        sb.AppendLine("    call BJDebugMsg(\"LEAKSAMPLE handles \" + I2S(GetHandleId(probe)))");
        sb.AppendLine("    call DestroyTrigger(probe)");
        sb.AppendLine("endfunction");
        sb.AppendLine();
        sb.AppendLine("function LeakHarnessDrive takes nothing returns nothing");
        foreach (var f in functions) sb.AppendLine($"    call {f}()");
        sb.AppendLine("endfunction");
        sb.AppendLine();
        sb.AppendLine("function LeakHarnessStart takes nothing returns nothing");
        sb.AppendLine("    call TimerStart(CreateTimer(), 0.03, true, function LeakHarnessDrive)");
        sb.AppendLine("    call TimerStart(CreateTimer(), 1.0, true, function LeakHarnessSample)");
        sb.AppendLine("endfunction");
        return sb.ToString();
    }

    private static string Lua(IReadOnlyList<string> functions)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- leak harness, generated by wc3ctl");
        sb.AppendLine("-- Drives the named hot leak candidates on a short timer so the runtime handle");
        sb.AppendLine("-- and memory slope becomes measurable in seconds rather than in an hour.");
        sb.AppendLine("-- Each driven function is a periodic callback that must take nothing.");
        sb.AppendLine();
        sb.AppendLine("function LeakHarnessSample()");
        sb.AppendLine("    local probe = CreateTrigger()");
        sb.AppendLine("    BJDebugMsg(\"LEAKSAMPLE handles \" .. tostring(GetHandleId(probe)))");
        sb.AppendLine("    DestroyTrigger(probe)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("function LeakHarnessDrive()");
        foreach (var f in functions) sb.AppendLine($"    {f}()");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("function LeakHarnessStart()");
        sb.AppendLine("    TimerStart(CreateTimer(), 0.03, true, LeakHarnessDrive)");
        sb.AppendLine("    TimerStart(CreateTimer(), 1.0, true, LeakHarnessSample)");
        sb.AppendLine("end");
        return sb.ToString();
    }
}
